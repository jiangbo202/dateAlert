const dicts: Record<Locale, Dict> = { 'zh-CN': zhCN, 'zh-TW': zhTW, en };

export const locale = ref<Locale>('zh-CN');

export function setLocale(next: Locale): void {
  locale.value = next;
  document.documentElement.lang = next;
  document.title = t('brand');
  localStorage.setItem('lang', next);
}

export function normalizeLocale(value: string | undefined | null): Locale | null {
  if (!value) return null;
  const lower = value.toLowerCase();
  if (lower.startsWith('zh-tw') || lower.startsWith('zh-hk') || lower.startsWith('zh-hant')) return 'zh-TW';
  if (lower.startsWith('zh')) return 'zh-CN';
  if (lower.startsWith('en')) return 'en';
  return null;
}

export function resolveLocale(preferred?: string): Locale {
  const stored = normalizeLocale(localStorage.getItem('lang'));
  if (stored) return stored;
  const fromServer = normalizeLocale(preferred);
  if (fromServer) return fromServer;
  const browser = normalizeLocale(navigator.language);
  return browser ?? 'zh-CN';
}

export function initLocale(preferred?: string): void {
  setLocale(resolveLocale(preferred));
}

export function t(key: string, params?: Record<string, string | number>): string {
  const dict = dicts[locale.value] ?? dicts['zh-CN'];
  let text = dict[key] ?? dicts['zh-CN'][key] ?? key;
  if (params) {
    for (const [name, value] of Object.entries(params)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}

export function useI18n() {
  return { t, locale, setLocale };
}
